import numpy as np
import arabic_reshaper
#-------------------------------------------------------
# install: pip install python-bidi
from bidi.algorithm import get_display
#-------------------------------------------------------

# ******************************************
# ورودی: ۳ ویژگی
# لایه پنهان: ۴ نورون + تابع فعال‌سازی ReLU
# لایه خروجی: ۱ نورون + تابع فعال‌سازی Sigmoid
# *******************************************

# -------------------------------
# توابع فعال‌سازی
# -------------------------------
def relu(z):
    return np.maximum(0, z)

def sigmoid(z):
    return 1 / (1 + np.exp(-z))

# -------------------------------
# تعریف وزن‌ها و بایاس‌ها (مقدارهای فرضی)
# -------------------------------

# وزن‌های لایه پنهان (۴ نورون، ۳ ورودی)
W1 = np.array([
    [0.2, 0.4, -0.1],
    [0.5, -0.3, 0.2],
    [-0.4, 0.1, 0.6],
    [0.3, 0.2, -0.5]
])
b1 = np.array([0.1, -0.2, 0.05, 0.3])

# وزن‌های لایه خروجی (۱ نورون، ۴ ورودی از لایه پنهان)
W2 = np.array([0.6, -0.3, 0.4, 0.2])
b2 = 0.1

# -------------------------------
# ورودی نمونه
# -------------------------------
x = np.array([0.5, 0.3, 0.8])

# -------------------------------
# مسیر جلو (Forward Pass)
# -------------------------------

# لایه پنهان
z1 = np.dot(W1, x) + b1
a1 = relu(z1)                # خروجی لایه پنهان بعد از ReLU
print(get_display(arabic_reshaper.reshape(f"خروجی لایه پنهان (بعد از ReLU):")))
print(a1)

# لایه خروجی
z2 = np.dot(W2, a1) + b2
y_hat = sigmoid(z2)          # خروجی نهایی
print(get_display(arabic_reshaper.reshape(f"\nخروجی نهایی شبکه (احتمال):")))
print(y_hat)